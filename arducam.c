/**
 * =============================================================================
 *  Arducam 2MP Plus (OV2640) — Driver Implementation
 *  Target: NUCLEO-L4R5ZI-P
 * =============================================================================
 *
 *  ArduChip on SPI3: PG9=SCK  PG10=MISO  PG11=MOSI  PG12=CS (GPIO)
 *  OV2640  on I2C2:  PF0=SDA  PF1=SCL    Slave addr 0x60
 *
 *  SPI protocol:
 *    bit[7]   = 1 for write, 0 for read
 *    bit[6:0] = register address
 *    Max SPI clock: 8 MHz, Mode 0 (CPOL=0 CPHA=0)
 */

#include "arducam.h"
#include "ov2640_regs.h"
#include "main.h"

/* ── Peripheral handles (generated by CubeMX) ────────────────────────────── */
extern SPI_HandleTypeDef hspi3;
extern I2C_HandleTypeDef hi2c2;

/* ═══════════════════════════════════════════════════════════════════════════
 *  LOW-LEVEL SPI (ArduChip)
 * ═══════════════════════════════════════════════════════════════════════════ */

/* Assert camera CS (PG12) low. */
static inline void cam_cs_low(void) {
    HAL_GPIO_WritePin(GPIOG, GPIO_PIN_12, GPIO_PIN_RESET);
}

/* Deassert camera CS (PG12) high. */
static inline void cam_cs_high(void) {
    HAL_GPIO_WritePin(GPIOG, GPIO_PIN_12, GPIO_PIN_SET);
}

/* Write one byte to an ArduChip register. */
void cam_write_reg(uint8_t addr, uint8_t data)
{
    uint8_t tx[2];
    tx[0] = addr | 0x80;   /* bit[7]=1 → write */
    tx[1] = data;
    cam_cs_low();
    HAL_SPI_Transmit(&hspi3, tx, 2, HAL_MAX_DELAY);
    cam_cs_high();
}

/* Read one byte from an ArduChip register. */
uint8_t cam_read_reg(uint8_t addr)
{
    uint8_t tx[2], rx[2];
    tx[0] = addr & 0x7F;   /* bit[7]=0 → read */
    tx[1] = 0x00;           /* dummy byte */
    cam_cs_low();
    HAL_SPI_TransmitReceive(&hspi3, tx, rx, 2, HAL_MAX_DELAY);
    cam_cs_high();
    return rx[1];            /* data appears on second byte */
}

/* ═══════════════════════════════════════════════════════════════════════════
 *  LOW-LEVEL I2C (OV2640 sensor registers)
 * ═══════════════════════════════════════════════════════════════════════════ */

/* Write one OV2640 register (8-bit addr, 8-bit data) via I2C. */
void cam_sensor_write(uint8_t reg, uint8_t val)
{
    uint8_t buf[2] = { reg, val };
    HAL_I2C_Master_Transmit(&hi2c2, OV2640_I2C_ADDR, buf, 2, HAL_MAX_DELAY);
}

/* Read one OV2640 register via I2C. */
uint8_t cam_sensor_read(uint8_t reg)
{
    uint8_t val = 0;
    HAL_I2C_Master_Transmit(&hi2c2, OV2640_I2C_ADDR, &reg, 1, HAL_MAX_DELAY);
    HAL_I2C_Master_Receive(&hi2c2, OV2640_I2C_ADDR | 0x01, &val, 1, HAL_MAX_DELAY);
    return val;
}

/* Write an entire register table to the OV2640. */
static void cam_sensor_write_regs(const sensor_reg_t *table)
{
    while (table->reg != 0xFF || table->val != 0xFF) {
        cam_sensor_write(table->reg, table->val);
        table++;
    }
}

/* ═══════════════════════════════════════════════════════════════════════════
 *  FIFO HELPERS
 * ═══════════════════════════════════════════════════════════════════════════ */

/* Flush the FIFO (reset read pointer + clear done flag). */
static void cam_flush_fifo(void)
{
    cam_write_reg(ARDUCHIP_FIFO_CR, FIFO_CLEAR_MASK);
}

/* Reset the FIFO read/write pointers. */
static void cam_clear_fifo(void)
{
    cam_write_reg(ARDUCHIP_FIFO_CR, FIFO_CLEAR_MASK);
    cam_write_reg(ARDUCHIP_FIFO_CR, FIFO_RDPTR_RST_MASK);
    cam_write_reg(ARDUCHIP_FIFO_CR, FIFO_WRPTR_RST_MASK);
}

/* Start a capture. */
static void cam_start_capture(void)
{
    cam_write_reg(ARDUCHIP_FIFO_CR, FIFO_START_MASK);
}

/* Check if capture is done. */
static bool cam_capture_done(void)
{
    return (cam_read_reg(ARDUCHIP_TRIG) & CAP_DONE_MASK) != 0;
}

/* ═══════════════════════════════════════════════════════════════════════════
 *  PUBLIC API
 * ═══════════════════════════════════════════════════════════════════════════ */

/* Read the ArduChip version register (expect 0x40 for 2MP). */
uint8_t cam_read_chip_version(void)
{
    return cam_read_reg(ARDUCHIP_REV);
}

/* Full init: SPI test, OV2640 ID check, load JPEG defaults at 320×240. */
cam_status_t cam_init(void)
{
    /* Deselect camera. */
    cam_cs_high();
    HAL_Delay(100);

    /* ── Test SPI link: write 0x55 to test register, read it back. ──── */
    cam_write_reg(ARDUCHIP_TEST, 0x55);
    uint8_t test = cam_read_reg(ARDUCHIP_TEST);
    if (test != 0x55) return CAM_ERR_SPI;

    /* ── Reset the OV2640 sensor. ─────────────────────────────────────── */
    cam_sensor_write(0xFF, 0x01);   /* Select sensor register bank */
    cam_sensor_write(0x12, 0x80);   /* Software reset */
    HAL_Delay(100);

    /* ── Verify OV2640 chip ID. ───────────────────────────────────────── */
    cam_sensor_write(0xFF, 0x01);
    uint8_t vid = cam_sensor_read(OV2640_CHIPID_HIGH);
    uint8_t pid = cam_sensor_read(OV2640_CHIPID_LOW);
    if (vid != 0x26 || (pid != 0x41 && pid != 0x42))
        return CAM_ERR_SENSOR_ID;

    /* ── Load JPEG mode defaults. ─────────────────────────────────────── */
    cam_sensor_write_regs(OV2640_JPEG_INIT);
    cam_sensor_write_regs(OV2640_YUV422);
    cam_sensor_write_regs(OV2640_JPEG);
    cam_sensor_write(0xFF, 0x01);
    cam_sensor_write(0x15, 0x00);

    /* ── Default resolution: 320×240. ─────────────────────────────────── */
    cam_sensor_write_regs(OV2640_320x240_JPEG);

    /* ── Set ArduChip to MCU-to-LCD mode. ─────────────────────────────── */
    cam_write_reg(ARDUCHIP_MODE, MCU2LCD_MODE);

    return CAM_OK;
}

/* Set output format (JPEG recommended; BMP uses much more FIFO space). */
void cam_set_format(cam_format_t fmt)
{
    if (fmt == CAM_FMT_JPEG) {
        cam_sensor_write_regs(OV2640_JPEG_INIT);
        cam_sensor_write_regs(OV2640_YUV422);
        cam_sensor_write_regs(OV2640_JPEG);
        cam_sensor_write(0xFF, 0x01);
        cam_sensor_write(0x15, 0x00);
    }
    /* BMP mode would load OV2640_QVGA table — omitted to save flash. */
}

/* Set JPEG output resolution. */
void cam_set_jpeg_size(cam_jpeg_size_t size)
{
    if (size > CAM_1600x1200) return;
    cam_sensor_write_regs(OV2640_JPEG_SIZE_TBL[size]);
}

/* Capture a single frame.  Blocks until done or timeout (~5 s). */
cam_status_t cam_capture(void)
{
    /* Flush + reset FIFO. */
    cam_clear_fifo();

    /* Start capture. */
    cam_start_capture();

    /* Poll for capture done (bit 3 of register 0x41). */
    uint32_t start = HAL_GetTick();
    while (!cam_capture_done()) {
        if (HAL_GetTick() - start > 5000)
            return CAM_ERR_TIMEOUT;
    }

    return CAM_OK;
}

/* Get FIFO byte count after capture (up to 8 MB). */
uint32_t cam_fifo_length(void)
{
    uint32_t len;
    len  = cam_read_reg(ARDUCHIP_FIFO_SIZE1);
    len |= (uint32_t)cam_read_reg(ARDUCHIP_FIFO_SIZE2) << 8;
    len |= (uint32_t)(cam_read_reg(ARDUCHIP_FIFO_SIZE3) & 0x07) << 16;
    return len;
}

/* Burst-read `len` bytes from FIFO into `buf`. */
void cam_fifo_read(uint8_t *buf, uint32_t len)
{
    uint8_t cmd = ARDUCHIP_FIFO_BURST;

    cam_cs_low();

    /* Send burst-read command. */
    HAL_SPI_Transmit(&hspi3, &cmd, 1, HAL_MAX_DELAY);

    /* First byte back is a dummy — discard it. */
    uint8_t dummy;
    HAL_SPI_Receive(&hspi3, &dummy, 1, HAL_MAX_DELAY);

    /* Read actual image data. */
    HAL_SPI_Receive(&hspi3, buf, len, HAL_MAX_DELAY);

    cam_cs_high();
}
